#!/usr/bin/env node
// Write the provenance receipt consumed by tools/check-release.mjs. This is
// deliberately fed by the build container after the native archives and the
// pinned Rust checkout have been selected; it never invents artifact hashes.

import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { collectKernelDumps } from './latexml-kernel-dumps.mjs'

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`)
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback
}
const dist = path.resolve(arg('dist', 'wasm-build/dist'))
const source = path.resolve(arg('source', process.env.LATEXML_SOURCE_DIR || '/build/latexml/source'))
const refFile = path.resolve(arg('ref', 'wasm-build/latexml-source.ref'))
const libxmlDir = path.resolve(arg('libxml-dir', '/build/latexml/libxml'))
const sha = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex')
const read = (file) => fs.readFileSync(file, 'utf8').trim()
const ref = Object.fromEntries(read(refFile).split(/\n/).filter(Boolean).map((line) => line.split('=', 2)))
if (!ref.repository || !/^[a-f0-9]{40}$/.test(ref.commit)) throw new Error('latexml-source.ref must pin a repository and commit')
if (!fs.existsSync(source) || !fs.existsSync(path.join(source, '.git'))) throw new Error(`LaTeXML checkout missing: ${source}`)
const sourceCommit = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
if (sourceCommit !== ref.commit) throw new Error(`LaTeXML checkout is ${sourceCommit}, expected ${ref.commit}`)

const css = [
  'latexml.css', 'LaTeXML.css', 'LaTeXML-blue.css', 'LaTeXML-marginpar.css',
  'LaTeXML-navbar-left.css', 'LaTeXML-navbar-right.css', 'ltx-amsart.css',
  'ltx-apj.css', 'ltx-article.css', 'ltx-book.css', 'ltx-listings.css',
  'ltx-report.css', 'ltx-svjour.css', 'ltx-ulem.css',
]
const artifactNames = ['latexml.js', 'latexml.wasm', 'latexml.worker.js', ...css]
const artifacts = Object.fromEntries(artifactNames
  .filter((name) => fs.existsSync(path.join(dist, name)))
  .map((name) => {
    const file = path.join(dist, name)
    return [name, { bytes: fs.statSync(file).size, sha256: sha(file) }]
  }))
const mapFile = path.join(dist, 'latexml.map')
const linkMap = fs.existsSync(mapFile) ? { name: 'latexml.map', bytes: fs.statSync(mapFile).size, sha256: sha(mapFile) } : null

// Kernel snapshots are generated by tools/make_formats.sh inside the pinned
// checkout, using the TeX Live installation in the build image. They are
// embedded into the WASM by latexml_engine/build.rs, so retain the source
// filenames and hashes even though the text files are not release artifacts.
// A build may be made with LATEXML_SKIP_DUMPS=1 while iterating; that produces
// an empty list here and is rejected later by the release gate.
const kernelDumps = collectKernelDumps(source)

const sourceArchive = (name, version, url, checksum, license, notices) => ({
  name, version, source: url, sourceArchive: { url, sha256: checksum }, license, notices,
})
const verifyArchive = (file, expected, label) => {
  if (!fs.existsSync(file)) throw new Error(`native source archive missing: ${file}`)
  const actual = sha(file)
  if (actual !== expected) throw new Error(`${label} archive hash is ${actual}, expected ${expected}`)
}
const libxml2Sha = '74fc163217a3964257d3be39af943e08861263c4231f9ef5b496b6f6d4c7b2b6'
const libxsltSha = '85ca62cac0d41fc77d3f6033da9df6fd73d20ea2fc18b0a3609ffb4110e1baeb'
verifyArchive(path.join(libxmlDir, 'libxml2.tar.xz'), libxml2Sha, 'libxml2')
verifyArchive(path.join(libxmlDir, 'libxslt.tar.xz'), libxsltSha, 'libxslt')
for (const directory of ['libxml2-2.13.5', 'libxslt-1.1.42']) {
  if (!fs.existsSync(path.join(libxmlDir, directory))) throw new Error(`native source tree missing: ${path.join(libxmlDir, directory)}`)
}
const dependencies = [
  sourceArchive('libxml2', '2.13.5',
    'https://download.gnome.org/sources/libxml2/2.13/libxml2-2.13.5.tar.xz',
    libxml2Sha, 'MIT', ['LICENSES/libxml2-Copyright.txt']),
  sourceArchive('libxslt', '1.1.42',
    'https://download.gnome.org/sources/libxslt/1.1/libxslt-1.1.42.tar.xz',
    libxsltSha, 'MIT', ['LICENSES/libxslt-COPYING.txt']),
  {
    name: 'kpathsea', version: process.env.KPSE_REF || 'def12ffd4d6e46bae03b3e5c7ff6f5f14dced3ab',
    source: 'https://github.com/TeX-Live/texlive-source.git',
    sourcePath: 'texlive-source/texk/kpathsea', license: 'LGPL-2.1-or-later',
    notices: ['LICENSES/LGPL-2.1.txt'],
  },
]

const lock = path.join(source, 'Cargo.lock')
const wrapperLock = path.resolve(arg('wrapper-lock', 'wasm-build/latexml-wasm/Cargo.lock'))
// The wasm wrapper's lockfile is authoritative: it pins the exact graph Cargo
// linked into the browser module. The upstream checkout's lockfile, when one
// is present, describes a different native target and is only supplemental.
const lockFile = fs.existsSync(wrapperLock) ? wrapperLock : lock
const cargoLock = fs.existsSync(lockFile)
  ? {
      path: lockFile === wrapperLock ? 'repo/wasm-build/latexml-wasm/Cargo.lock' : 'latexml-oxide/Cargo.lock',
      sha256: sha(lockFile),
    }
  : null
const cargoDependencies = cargoLock
  ? read(lockFile).split('[[package]]').slice(1).map((chunk) => {
      const field = (name) => chunk.match(new RegExp(`^${name} = "([^"]+)"`, 'm'))?.[1]
      return { name: field('name'), version: field('version'), source: field('source') || null, checksum: field('checksum') || null }
    }).filter((entry) => entry.name && entry.version)
  : []
const marpa = cargoDependencies.find((entry) => entry.name === 'libmarpa-asf-sys')
if (marpa) {
  const marpaUrl = `https://crates.io/api/v1/crates/libmarpa-asf-sys/${marpa.version}/download`
  dependencies.push(marpa.checksum
    ? sourceArchive('libmarpa-asf-sys', marpa.version, marpaUrl, marpa.checksum,
      'MIT AND LGPL-2.1-or-later AND LGPL-3.0-or-later',
      ['LICENSES/libmarpa-COPYING.txt', 'LICENSES/libmarpa-COPYING.LESSER.txt'])
    : {
        name: 'libmarpa-asf-sys', version: marpa.version, source: marpaUrl,
        license: 'MIT AND LGPL-2.1-or-later AND LGPL-3.0-or-later',
        notices: ['LICENSES/libmarpa-COPYING.txt', 'LICENSES/libmarpa-COPYING.LESSER.txt'],
      })
}

const receipt = {
  schemaVersion: 1,
  family: 'latexml',
  toolchain: {
    emscripten: '6.0.9',
    emscriptenImage: 'emscripten/emsdk:6.0.9@sha256:96617f27fe16421588241def73908fd348a7f9d260440ed0d00b36dcf7a063cc',
    rust: 'nightly-2026-08-02',
  },
  source: { repository: ref.repository, commit: ref.commit, path: 'latexml-oxide/' },
  dependencies,
  cargo: { lockfile: cargoLock, packages: cargoDependencies },
  nativeSources: {
    libxml2: { directory: 'latexml-dependencies/libxml2-2.13.5', archiveSha256: dependencies[0].sourceArchive.sha256 },
    libxslt: { directory: 'latexml-dependencies/libxslt-1.1.42', archiveSha256: dependencies[1].sourceArchive.sha256 },
  },
  kernelDumps,
  linkMap,
  artifacts,
}
fs.writeFileSync(path.join(dist, 'latexml.build.json'), JSON.stringify(receipt, null, 2) + '\n')
